/**
 * Build-time helper: converts us-atlas TopoJSON into static SVG paths for the
 * Mid-Atlantic region used by the service-area section.
 *
 *   node scripts/generate-map.mjs
 *
 * Output: src/data/marylandMap.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TOPO = path.join(process.env.TEMP || '/tmp', 'opencode', 'states-10m.json');
const OUT = path.join(__dirname, '..', 'src', 'data', 'marylandMap.js');

const VIEW_W = 900;
const VIEW_H = 620;

const BOUNDS = { lonMin: -80.6, lonMax: -74.7, latMin: 37.4, latMax: 40.1 };
const LAT0 = ((BOUNDS.latMax + BOUNDS.latMin) / 2) * (Math.PI / 180);

const scale = Math.min(
  VIEW_W / ((BOUNDS.lonMax - BOUNDS.lonMin) * Math.cos(LAT0)),
  VIEW_H / (BOUNDS.latMax - BOUNDS.latMin),
);

const lonPx =
  (lon) => (lon - BOUNDS.lonMin) * Math.cos(LAT0) * scale +
  (VIEW_W - (BOUNDS.lonMax - BOUNDS.lonMin) * Math.cos(LAT0) * scale) / 2;
const latPx = (lat) => (BOUNDS.latMax - lat) * scale;

const round = (value) => Math.round(value * 10) / 10;

function ringToPath(ring) {
  let d = '';
  ring.forEach(([lon, lat], index) => {
    const x = round(lonPx(lon));
    const y = round(latPx(lat));
    d += `${index === 0 ? 'M' : 'L'}${x} ${y}`;
  });
  return `${d}Z`;
}

function geometryToPath(geometry) {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  let d = '';
  for (const polygon of polygons) {
    for (const ring of polygon) d += ringToPath(ring);
  }
  return d;
}

const topology = JSON.parse(fs.readFileSync(TOPO, 'utf8'));
const collection = feature(topology, topology.objects.states);

const CONTEXT_FIPS = {
  '42': 'pennsylvania',
  '51': 'virginia',
  '10': 'delaware',
  '54': 'westVirginia',
  '11': 'districtOfColumbia',
  '34': 'newJersey',
  '39': 'ohio',
  '24': 'maryland',
};

const paths = {};
for (const state of collection.features) {
  const fips = String(state.id).padStart(2, '0');
  const key = CONTEXT_FIPS[fips];
  if (key) paths[key] = geometryToPath(state.geometry);
}

const markers = [
  { id: 'millersville', label: 'Millersville', lat: 39.0534, lon: -76.5275, primary: true },
  { id: 'baltimore', label: 'Baltimore', lat: 39.2904, lon: -76.6122 },
  { id: 'annapolis', label: 'Annapolis', lat: 38.9784, lon: -76.4922 },
  { id: 'washington', label: 'Washington, DC', lat: 38.9072, lon: -77.0369 },
];

const out = `/**
 * Generated by scripts/generate-map.mjs from public us-atlas boundary data.
 * Do not edit by hand — re-run the script to update.
 */

export const mapMeta = {
  viewWidth: ${VIEW_W},
  viewHeight: ${VIEW_H},
  marker: {
    lat: 39.0534,
    lon: -76.5275,
    x: ${round(lonPx(-76.5275))},
    y: ${round(latPx(39.0534))},
  },
  points: {
${markers
  .map(
    (m) =>
      `    ${m.id}: { label: ${JSON.stringify(m.label)}, x: ${round(lonPx(m.lon))}, y: ${round(
        latPx(m.lat),
      )}, primary: ${Boolean(m.primary)} },`,
  )
  .join('\n')}
  },
};

export const mapPaths = {
${Object.entries(paths)
  .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
  .join('\n')}
};

export default { mapMeta, mapPaths };
`;

fs.writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${OUT}`);
console.log('states:', Object.keys(paths).join(', '));
console.log('maryland path length:', paths.maryland?.length ?? 0);
